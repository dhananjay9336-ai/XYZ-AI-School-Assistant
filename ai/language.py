def get_text(language, key, **kwargs):

    # Convert language name to language code
    code = LANGUAGES.get(
        language,
        "en"
    )

    # Get requested text
    text = TEXT.get(
        key,
        {}
    ).get(
        code
    )

    # If requested language is not available,
    # use English as fallback
    if text is None:

        text = TEXT.get(
            key,
            {}
        ).get(
            "en",
            ""
        )

    # Replace variables such as:
    # {attendance}
    # {name}
    # {request_id}

    return text.format(**kwargs)